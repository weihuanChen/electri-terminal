const evidencePaths = [
  "product.model",
  "sourcePayload.title",
  "evidencePayload.variants",
];

function productGroup({
  key,
  name,
  description,
  modelValues,
  modelOperator = "contains",
  differentiatorKey,
  differentiatorLabel,
  differentiatorValues,
  intentImpact,
  goal,
  selectionIntent,
}) {
  return {
    key,
    name,
    description,
    criteria: [
      {
        fieldPath: "product.model",
        operator: modelOperator,
        values: modelValues,
        required: true,
      },
    ],
    differentiators: [
      {
        key: differentiatorKey,
        label: differentiatorLabel,
        sourcePaths: evidencePaths,
        values: differentiatorValues,
        intentImpact,
      },
    ],
    goal,
    selectionIntent,
    evidencePaths,
  };
}

